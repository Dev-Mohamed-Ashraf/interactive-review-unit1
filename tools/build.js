#!/usr/bin/env node
/* =========================================================
 * tools/build.js — generates the offline layer.
 *   node tools/build.js
 * 1) sw.js       : service worker that pre-caches every app file
 *                  (version = hash of all files → updates roll out automatically)
 * Run it after ANY change; `node tests/run.js` fails if sw.js is stale.
 * (Icons: icons/icon.svg → PNGs with ImageMagick:
 *   magick -background none -density 384 icons/icon.svg -resize 512x512 icons/icon-512.png)
 * ========================================================= */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const INCLUDE_DIRS = ['css', 'js', 'vendor', 'fonts', 'img', 'icons', 'media'];
const RUNTIME_ONLY = /\.mp4$/; // big videos: cached on first play, not pre-downloaded
const INCLUDE_FILES = ['index.html', 'manifest.webmanifest'];

function listAssets() {
  const out = [...INCLUDE_FILES];
  INCLUDE_DIRS.forEach((d) => {
    (function walk(dir) {
      fs.readdirSync(path.join(ROOT, dir)).sort().forEach((f) => {
        const rel = `${dir}/${f}`;
        if (fs.statSync(path.join(ROOT, rel)).isDirectory()) walk(rel);
        else if (!RUNTIME_ONLY.test(rel)) out.push(rel);
      });
    })(d);
  });
  return out;
}

function version(assets) {
  const h = crypto.createHash('sha1');
  assets.forEach((a) => h.update(a).update(fs.readFileSync(path.join(ROOT, a))));
  return h.digest('hex').slice(0, 10);
}

function listVideos() {
  return fs.readdirSync(path.join(ROOT, 'media')).filter((f) => RUNTIME_ONLY.test(f)).sort().map((f) => `media/${f}`);
}

function build() {
  const assets = listAssets();
  const videos = listVideos();
  const v = version(assets);
  const sw = `/* GENERATED by tools/build.js — do not edit by hand. */
'use strict';
const VERSION = 'rv-u1-${v}';
const MEDIA = 'rv-media'; // videos live in their own cache: it survives app updates (no 40 MB re-download)
// CORE is downloaded at install (small: code, styles, fonts, icons).
// WARM (images, video posters) is fetched later when the page says it is idle.
const ALL = ${JSON.stringify(['./', ...assets], null, 2)};
const VIDEOS = ${JSON.stringify(videos, null, 2)};
const isWarm = (u) => u.startsWith('img/') || u.startsWith('media/');
const CORE = ALL.filter((u) => !isWarm(u));
const WARM = ALL.filter(isWarm);
const isVideo = (url) => url.pathname.endsWith('.mp4');

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(CORE)).then(() => self.skipWaiting()));
});

async function fill(cacheName, urls, onEach) {
  const c = await caches.open(cacheName);
  let failed = 0;
  for (const u of urls) {
    if (!(await c.match(u))) { try { await c.add(u); } catch (err) { failed++; } }
    if (onEach) onEach();
  }
  return failed;
}

self.addEventListener('message', (e) => {
  if (e.data === 'warm') { e.waitUntil(fill(VERSION, WARM)); return; }
  // "download everything for offline": app + images + the videos this device plays
  if (e.data && e.data.type === 'offline') {
    const videos = (e.data.videos || []).filter((u) => VIDEOS.includes(u));
    const total = CORE.length + WARM.length + videos.length;
    let done = 0;
    const client = e.source;
    const tell = (msg) => client && client.postMessage(msg);
    const step = () => { done++; if (done % 5 === 0 || done === total) tell({ type: 'offline-progress', done, total }); };
    e.waitUntil((async () => {
      let failed = await fill(VERSION, CORE, step);
      failed += await fill(VERSION, WARM, step);
      failed += await fill(MEDIA, videos, step);
      tell({ type: 'offline-done', ok: failed === 0, failed, total });
    })());
  }
});

self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((k) => k !== VERSION && k !== MEDIA).map((k) => caches.delete(k)));
    // drop videos that are no longer part of the app
    const m = await caches.open(MEDIA);
    for (const req of await m.keys()) { if (!VIDEOS.some((u) => req.url.endsWith(u))) await m.delete(req); }
    await self.clients.claim();
  })());
});

/** Safari plays video with Range requests: answer them from the cached file (206 slice). */
async function rangeFromCache(req) {
  const hit = await caches.match(req.url, { ignoreSearch: true });
  if (!hit) return fetch(req);
  const buf = await hit.arrayBuffer();
  // "bytes=START-END" (either side may be empty) — parsed without a regex (this text lives in a template literal)
  const [a, b] = (req.headers.get('range') || '').replace('bytes=', '').split('-');
  const size = buf.byteLength;
  const suffix = !a && b; // "bytes=-500" = the last 500 bytes
  const start = suffix ? Math.max(0, size - parseInt(b, 10)) : a ? parseInt(a, 10) : 0;
  const end = !suffix && b ? Math.min(parseInt(b, 10), size - 1) : size - 1;
  return new Response(buf.slice(start, end + 1), {
    status: 206,
    statusText: 'Partial Content',
    headers: { 'Content-Type': 'video/mp4', 'Content-Range': 'bytes ' + start + '-' + end + '/' + size, 'Content-Length': String(end - start + 1), 'Accept-Ranges': 'bytes' },
  });
}

// cache-first: works fully offline after the first visit (or after "download for offline")
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  const url = new URL(e.request.url);
  if (url.origin !== location.origin) return;
  if (e.request.headers.has('range')) { e.respondWith(rangeFromCache(e.request)); return; }
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).then((res) => {
    const copy = res.clone();
    if (res.status === 200) caches.open(isVideo(url) ? MEDIA : VERSION).then((c) => c.put(e.request, copy));
    return res;
  }).catch(() => (e.request.mode === 'navigate' ? caches.match('./') : Response.error()))));
});
`;
  fs.writeFileSync(path.join(ROOT, 'sw.js'), sw);
  console.log(`sw.js written — ${assets.length} assets + ${videos.length} videos on demand, version ${v}`);
  return { assets, v };
}

if (require.main === module) build();
module.exports = { listAssets, listVideos, version };
